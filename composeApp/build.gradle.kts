// ── build-time example files (GeneratedExamples.kt) ─────────────────────────
// The example rotation systems live as text files in composeApp/examples/ (copied there by
// hand from the rafla data, see doc/DEVELOPMENT.md). Every file is embedded as a string, so
// the app has them at once (no resource reads, no fetches on the web). The catalogue (names,
// groups, descriptions) is core/Examples.kt. Long files are split into chunks, since a JVM string
// constant holds at most 65535 bytes.
@CacheableTask
abstract class GenerateExamples : DefaultTask() {
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val examplesDir: DirectoryProperty
    @get:Input abstract val packageName: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun run() {
        val dir = examplesDir.get().asFile
        val files = dir.walkTopDown().filter { it.isFile && !it.name.startsWith(".") }
            .sortedBy { it.relativeTo(dir).invariantSeparatorsPath }.toList()
        val entries = files.joinToString(",\n") { file ->
            val chunks = file.readText(Charsets.UTF_8).chunked(CHUNK).joinToString(", ") { KotlinLiteral.of(it) }
            "        ${KotlinLiteral.of(file.relativeTo(dir).invariantSeparatorsPath)} to arrayOf($chunks)"
        }
        outputDir.get().asFile.apply { mkdirs() }.resolve("GeneratedExamples.kt").writeText(
            """
            |package ${packageName.get()}
            |
            |/**
            | * AUTO-GENERATED — DO NOT EDIT.
            | * Generated at build time by the generateExamples Gradle task from composeApp/examples/.
            | */
            |internal object GeneratedExamples {
            |    /** The text of every example file (in chunks), by its path below composeApp/examples/. */
            |    val FILES: Map<String, Array<String>> = mapOf(
            |$entries,
            |    )
            |}
            |""".trimMargin(),
            Charsets.UTF_8,
        )
    }

    private companion object {
        /** Characters per string literal (the files are ASCII). */
        const val CHUNK = 60000
    }
}

val generateExamples = tasks.register<GenerateExamples>("generateExamples") {
    examplesDir.set(layout.projectDirectory.dir("examples"))
    packageName.set("org.bytefred.rotsysview.core")
    outputDir.set(layout.buildDirectory.dir("generated/examples"))
}

